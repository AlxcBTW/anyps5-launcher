out.push("        }");
out.push("    }");
out.push("");
out.push("    const fn english(self) -> &'static str {");
out.push("        match self {");
for (const k of keys) out.push(`            Key::${pascal(k)} => ${lit(en.get(k))},`);
out.push("        }");
out.push("    }");
out.push("");
out.push("    const fn turkish(self) -> &'static str {");
out.push("        match self {");
for (const k of keys) out.push(`            Key::${pascal(k)} => ${lit(tr.get(k))},`);
out.push("        }");
out.push("    }");
out.push("}");
