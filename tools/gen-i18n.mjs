out.push("#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]");
out.push("pub enum Key {");
for (const k of keys) out.push(`    ${pascal(k)},`);
out.push("}");
out.push("");
out.push("impl Key {");
out.push(`    /// All keys in declaration order.`);
out.push(`    pub const ALL: [Key; ${keys.length}] = [`);
for (const k of keys) out.push(`        Key::${pascal(k)},`);
out.push("    ];");
out.push("");
